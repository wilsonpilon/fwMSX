// Teste do montador (fwasm) contra os arquivos golden gerados pelo asMSX de verdade (tools/asmdiff). Cada caso
// monta o mesmo fonte e compara codigo de saida, mensagens e arquivos de saida.
//
// Variaveis de ambiente (para depurar): FWASM_TEST_ONLY=<trecho do nome>, FWASM_TEST_VERBOSE=1,
// FWASM_TEST_SHOW=<n> (quantas falhas detalhar, padrao 12).
#include <cstdio>
#include <cstdlib>
#include <map>
#include <string>
#include <vector>

#include "../../src/asm/cpp/assembler.h"
#include "golden_reader.h"

namespace {

std::vector<uint8_t> FromHex(const std::string &hex) {
    std::vector<uint8_t> out;
    for (size_t i = 0; i + 1 < hex.size(); i += 2) out.push_back(static_cast<uint8_t>(std::stoi(hex.substr(i, 2), nullptr, 16)));
    return out;
}

std::string ToHex(const std::vector<uint8_t> &d, size_t limit = 40) {
    static const char *h = "0123456789abcdef";
    std::string s;
    for (size_t i = 0; i < d.size() && i < limit; ++i) {
        s += h[d[i] >> 4];
        s += h[d[i] & 15];
    }
    if (d.size() > limit) s += "..(" + std::to_string(d.size()) + ")";
    return s;
}

class MemFiles : public fwasm::FileProvider {
public:
    std::map<std::string, std::vector<uint8_t>> files;
    bool Read(const std::string &path, std::vector<uint8_t> &data) override {
        auto it = files.find(path);
        if (it == files.end()) return false;
        data = it->second;
        return true;
    }
};

// O cabecalho dos .sym/.txt cita o programa que os gerou; comparamos sem essa linha.
std::string MaskGenerated(std::string s) {
    const std::string key = "; generated by ";
    size_t p = s.find(key);
    if (p != std::string::npos) {
        size_t e = s.find("\r\n", p);
        s.erase(p, (e == std::string::npos ? s.size() : e) - p);
    }
    return s;
}

unsigned Crc32(const std::vector<uint8_t> &d) {
    unsigned crc = 0xFFFFFFFFu;
    for (const uint8_t b : d) {
        crc ^= b;
        for (int k = 0; k < 8; ++k) crc = (crc >> 1) ^ (0xEDB88320u & (0u - (crc & 1u)));
    }
    return ~crc;
}

std::string AsText(const std::vector<uint8_t> &d) { return std::string(d.begin(), d.end()); }

struct Stats {
    int total = 0, passed = 0, skipped = 0;
};

bool Check(const asmtest::GoldenCase &c, std::string &why) {
    MemFiles fs;
    for (const auto &kv : c.files) fs.files[kv.first] = FromHex(kv.second);
    fwasm::AsmOptions opts;
    for (const std::string &a : c.args)
        if (a == "-z") opts.zilog = true;
    const fwasm::AsmResult r = fwasm::Assemble("x.asm", c.source, opts, &fs);

    if (r.rc != c.rc) {
        why = "rc " + std::to_string(r.rc) + " (esperado " + std::to_string(c.rc) + ")";
        for (const auto &m : r.msgs) why += "\n      meu: " + m;
        for (const auto &m : c.msgs) why += "\n      ref: " + m;
        return false;
    }
    if (r.msgs != c.msgs) {
        why = "mensagens diferentes";
        for (const auto &m : r.msgs) why += "\n      meu: " + m;
        for (const auto &m : c.msgs) why += "\n      ref: " + m;
        return false;
    }
    for (const auto &kv : c.outs) {
        auto it = r.outs.find(kv.first);
        if (it == r.outs.end()) {
            why = "falta a saida '" + kv.first + "'";
            return false;
        }
        const std::vector<uint8_t> want = FromHex(kv.second);
        if (kv.first == "sym" || kv.first == "txt") {
            if (MaskGenerated(AsText(it->second)) != MaskGenerated(AsText(want))) {
                why = "conteudo de '" + kv.first + "' diferente\n      meu: " + AsText(it->second) + "\n      ref: " + AsText(want);
                return false;
            }
        } else if (it->second != want) {
            why = "bytes de '" + kv.first + "' diferentes\n      meu: " + ToHex(it->second) + "\n      ref: " + ToHex(want);
            return false;
        }
    }
    for (const auto &kv : c.outs_crc) {
        auto it = r.outs.find(kv.first);
        if (it == r.outs.end()) {
            why = "falta a saida '" + kv.first + "'";
            return false;
        }
        const unsigned crc = Crc32(it->second);
        if (it->second.size() != kv.second.first || crc != kv.second.second) {
            char buf[96];
            std::snprintf(buf, sizeof(buf), "tamanho %zu crc %08x (esperado %zu, %08x)", it->second.size(), crc, kv.second.first, kv.second.second);
            why = "bytes de '" + kv.first + "' diferentes: " + buf;
            return false;
        }
    }
    for (const auto &kv : r.outs) {
        if (!c.outs.count(kv.first) && !c.outs_crc.count(kv.first)) {
            why = "saida a mais: '" + kv.first + "'";
            return false;
        }
    }
    return true;
}


// Extensoes do fwasm que o asMSX nao tem (nao ha' golden): BOM UTF-8 e UTF-8 em comentarios/strings, a tabela de simbolos e o mapa de linhas,
// o formato/mapper e o aviso de marcadores para o depurador. Conferidos contra o asMSX a mao: sem BOM os bytes de UTF-8 saem crus, iguais.
int ExtraChecks() {
    int bad = 0;
    auto check = [&](bool ok, const char *what) {
        std::printf("[%s] %s\n", ok ? "PASS" : "FAIL", what);
        if (!ok) ++bad;
    };
    MemFiles none;
    fwasm::AsmOptions o;

    const std::string body = ".org 4000h\n db \"caf\xC3\xA9\"\n; \xC3\xA7 comentario\nnop ; \xC3\xA7\n";
    const fwasm::AsmResult plain = fwasm::Assemble("x.asm", body, o, &none);
    const fwasm::AsmResult bom = fwasm::Assemble("x.asm", std::string("\xEF\xBB\xBF") + body, o, &none);
    check(plain.rc == 0 && plain.outs.count("z80") && plain.outs.at("z80") == std::vector<uint8_t>({'c', 'a', 'f', 0xC3, 0xA9, 0x00}), "UTF-8 em string e comentario: os bytes saem crus (igual ao asMSX)");
    check(bom.rc == 0 && bom.outs == plain.outs, "BOM UTF-8 no inicio do fonte e' ignorado (o asMSX para sem gerar nada)");

    // BOM tambem no arquivo incluido
    MemFiles inc;
    inc.files["inc.asm"] = FromHex("EFBBBF6E6F700A"); // BOM + "nop\n"
    const fwasm::AsmResult with_inc = fwasm::Assemble("x.asm", ".org 4000h\n.include \"inc.asm\"\n", o, &inc);
    check(with_inc.rc == 0 && with_inc.outs.count("z80") && with_inc.outs.at("z80") == std::vector<uint8_t>({0x00}), "BOM no arquivo .include tambem e' ignorado");

    // simbolos, formato, mapper e marcadores
    const std::string rom = ".page 1\n.rom\n.start inicio\ninicio:\n ld a,1\nK .equ 5\n.debug \"x\"\nloop: jr loop\n";
    const fwasm::AsmResult r = fwasm::Assemble("x.asm", rom, o, &none);
    bool has_inicio = false, has_loop = false, has_k = false;
    for (const fwasm::SymbolRec &sy : r.symbols) {
        has_inicio = has_inicio || (sy.name == "inicio" && sy.is_label && sy.value == 0x4010);
        has_loop = has_loop || (sy.name == "loop" && sy.is_label);
        has_k = has_k || (sy.name == "K" && !sy.is_label && sy.value == 5);
    }
    check(r.rc == 0 && r.format == "rom" && has_inicio && has_loop && has_k, "AsmResult::symbols (rotulos e constantes) e format");
    check(r.uses_markers, "AsmResult::uses_markers quando o fonte tem .debug");
    const fwasm::AsmResult clean = fwasm::Assemble("x.asm", ".org 4000h\n nop\n", o, &none);
    check(!clean.uses_markers && clean.symbols.empty() && clean.format.empty(), "sem marcadores/simbolos/formato: tudo vazio");
    const fwasm::AsmResult mega = fwasm::Assemble("x.asm", ".megarom ascii8\n.page 1\n.subpage 0 at 4000h\n.start 4010h\n nop\n", o, &none);
    check(mega.format == "megarom" && mega.mapper == "ascii8", "AsmResult::format/mapper de uma MegaROM");

    // .BASIC sem .CAS: want_tape monta a fita assim mesmo
    o.want_tape = true;
    const fwasm::AsmResult bas = fwasm::Assemble("x.asm", ".bios\n.org 0d000h\n.basic\n ret\n", o, &none);
    check(bas.rc == 0 && bas.outs.count("cas") && bas.msgs.empty(), "want_tape: gera o .cas de um .BASIC sem a diretiva, sem mensagem extra");
    o.want_tape = false;
    const fwasm::AsmResult bas2 = fwasm::Assemble("x.asm", ".bios\n.org 0d000h\n.basic\n ret\n", o, &none);
    check(bas2.rc == 0 && !bas2.outs.count("cas"), "sem want_tape e sem .CAS: nenhuma fita");

    // listagem: arquivo e linha de cada endereco (base do `src` do depurador)
    o.want_listing = true;
    const fwasm::AsmResult lst = fwasm::Assemble("x.asm", ".org 4000h\n nop\n ld a,1\n", o, &none);
    bool l2 = false, l3 = false;
    for (const fwasm::ListEntry &e : lst.listing) {
        l2 = l2 || (e.line == 2 && e.addr == 0x4000 && e.bytes.size() == 1);
        l3 = l3 || (e.line == 3 && e.addr == 0x4001 && e.bytes.size() == 2);
    }
    check(l2 && l3, "listing: endereco e linha de cada instrucao");
    return bad;
}

} // namespace

int main() {
    const char *only = std::getenv("FWASM_TEST_ONLY");
    const bool verbose = std::getenv("FWASM_TEST_VERBOSE") != nullptr;
    const int show = std::getenv("FWASM_TEST_SHOW") ? std::atoi(std::getenv("FWASM_TEST_SHOW")) : 12;
    const std::string dir = std::string(FWMSX_SOURCE_DIR) + "/tests/asm/golden/";
    int failures_shown = 0;
    int bad = 0;
    for (const char *file : {"instr.golden", "expr.golden", "misc.golden", "lang.golden", "formats.golden"}) {
        const std::vector<asmtest::GoldenCase> cases = asmtest::ReadGolden(dir + file);
        if (cases.empty()) {
            std::printf("[SKIP] %s nao encontrado em '%s'\n", file, dir.c_str());
            continue;
        }
        Stats st;
        for (const auto &c : cases) {
            if (only && c.name.find(only) == std::string::npos) continue;
            bool skip = false;
            for (const auto &a : c.args)
                if (a != "-z") skip = true;
            if (skip) {
                ++st.skipped;
                continue;
            }
            ++st.total;
            std::string why;
            if (Check(c, why)) {
                ++st.passed;
                if (verbose) std::printf("[PASS] %s\n", c.name.c_str());
            } else {
                ++bad;
                if (failures_shown++ < show || verbose) {
                    std::printf("[FAIL] %s/%s: %s\n   fonte:\n", file, c.name.c_str(), why.c_str());
                    std::string src = c.source;
                    size_t p = 0;
                    while (p < src.size()) {
                        size_t e = src.find('\n', p);
                        std::printf("      | %s\n", src.substr(p, e == std::string::npos ? std::string::npos : e - p).c_str());
                        if (e == std::string::npos) break;
                        p = e + 1;
                    }
                }
            }
        }
        std::printf("%-14s %d/%d casos passaram (%d ignorados)\n", file, st.passed, st.total, st.skipped);
    }
    bad += ExtraChecks();
    if (bad) std::printf("\nFALHOU: %d caso(s)\n", bad);
    else std::printf("\nOK\n");
    return bad ? 1 : 0;
}
