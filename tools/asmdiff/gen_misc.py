def main():
    def run(c):
        name, src, files, args = c
        return run_case(src, extra_args=args, files=files)

    with ThreadPoolExecutor(max_workers=12) as ex:
        results = list(ex.map(run, CASES))
    cases = [(n, s, r, f, a) for (n, s, f, a), r in zip(CASES, results)]
    out = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "asm", "golden", "lang.golden")
    write_golden(out, cases)
    ok = sum(1 for r in results if r["rc"] == 0)
    print("casos:", len(CASES), "aceitos:", ok, "recusados:", len(CASES) - ok, file=sys.stderr)


if __name__ == "__main__":
    main()
